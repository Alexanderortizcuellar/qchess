# ---------- Data structures ----------


# Each puzzle becomes normalized to:
#   start_fen: str
#   line_uci: List[str]  (expected sequence, includes both sides)
@dataclass
class Puzzle:
    start_fen: str
    line_uci: List[str]
    title: str = ""


# ---------- Puzzler engine (signals-first) ----------


class Puzzler(QObject):
    """
    Puzzler: validates moves against a pre-defined expected line.
    Accepts inputs as (FEN, moves) or PGN strings. Emits signals
    to keep the UI decoupled from puzzle logic.

    Conventions:
      * User plays the side indicated by start_fen side-to-move.
      * Opponent replies (odd indices from expected line) are auto-played.
    """

    puzzleChanged = pyqtSignal(str, dict)  # fen, info
    moveResult = pyqtSignal(bool, str, dict)  # correct, fen, info
    scoreChanged = pyqtSignal(int, int)  # correct_count, failed_count
    hintAvailable = pyqtSignal(str, int, int)  # uci, from_sq, to_sq

    def __init__(
        self,
        raw_puzzles: List[Union[Tuple[str, Union[str, List[str]]], str]],
        parent=None,
    ):
        super().__init__(parent)
        self._puzzles: List[Puzzle] = self._parse_puzzles(raw_puzzles)
        self.total_puzzles = len(self._puzzles)
        self._idx: int = 0
        self._board_truth: chess.Board = chess.Board()
        self._expected: List[str] = []
        self._user_color: bool = chess.WHITE
        self._autoplaying: bool = False

        # simple score model (can be extended with weights, streaks, time, etc.)
        self.correct_count = 0
        self.failed_count = 0

        if self._puzzles:
            self._load_puzzle(0)

    # ---------- Public API ----------

    def next_puzzle(self):
        if not self._puzzles:
            return
        self._idx = (self._idx + 1) % len(self._puzzles)
        self._load_puzzle(self._idx)

    def retry_puzzle(self):
        if not self._puzzles:
            return
        self._load_puzzle(self._idx)

    @QtCore.pyqtSlot(str)
    def check_move(self, played_uci: str):
        """
        Validate a user move. This should be connected to ChessBoard.moveMade (str uci).
        If wrong, emit moveResult(False, fen, info). If correct, pop and possibly
        autoplay opponent reply moves, then emit result.
        """
        if self._autoplaying:
            # Ignore moveMade signals generated by our own autoplay
            return

        info = {
            "puzzle_index": self._idx + 1,
            "total_puzzles": len(self._puzzles),
            "played": played_uci,
            "expected": self._expected[0] if self._expected else None,
            "remaining": len(self._expected),
            "solved": False,
            "message": "",
        }

        if not self._expected:
            info["message"] = "No expected moves remain; puzzle already finished."
            self.moveResult.emit(True, self._board_truth.fen(), info)
            return

        expected_uci = self._expected[0]

        if played_uci == expected_uci:
            # Accept and advance
            move = chess.Move.from_uci(played_uci)
            if move not in self._board_truth.legal_moves:
                # Shouldn't happen, but guard anyway if UI board was desynced
                info["message"] = (
                    "Move matched expected UCI but was illegal in truth board."
                )
                self.failed_count += 1
                self.scoreChanged.emit(self.correct_count, self.failed_count)
                self.moveResult.emit(False, self._board_truth.fen(), info)
                return

            # Apply to truth board and pop expectation
            self._board_truth.push(move)
            self._expected.pop(0)

            # If opponent is to move next, autoplay as long as expected remains and
            # it's not user to move.
            self._maybe_autoplay_opponent()

            # Check solved
            if not self._expected:
                self.correct_count += 1
                info["solved"] = True
                info["message"] = "Puzzle solved!"
                self.scoreChanged.emit(self.correct_count, self.failed_count)
                self.moveResult.emit(True, self._board_truth.fen(), info)
            else:
                info["message"] = "Correct."
                self.moveResult.emit(True, self._board_truth.fen(), info)

        else:
            # Wrong move
            self.failed_count += 1
            info["message"] = "Wrong move."
            self.scoreChanged.emit(self.correct_count, self.failed_count)
            # Do not change truth board; UI can undo the last move to stay in sync
            self.moveResult.emit(False, self._board_truth.fen(), info)

    def request_hint(self):
        """Emit the next user move as a hint (arrow)."""
        if not self._expected:
            return
        next_uci = self._expected[0]
        move = chess.Move.from_uci(next_uci)
        self.hintAvailable.emit(next_uci, move.from_square, move.to_square)

    # ---------- Internals ----------

    def _load_puzzle(self, idx: int):
        puzzle = self._puzzles[idx]
        self._board_truth = chess.Board(puzzle.start_fen)
        self._expected = list(puzzle.line_uci)  # copy
        self._user_color = self._board_truth.turn

        info = {
            "puzzle_index": idx + 1,
            "total_puzzles": len(self._puzzles),
            "title": puzzle.title or f"Puzzle {idx+1}",
            "user_color": "White" if self._user_color == chess.WHITE else "Black",
            "total_moves_in_line": len(self._expected),
        }

        self.puzzleChanged.emit(self._board_truth.fen(), info)

        # If first to move is opponent (edge case if line starts with reply), autoplay
        self._maybe_autoplay_opponent()

    def _maybe_autoplay_opponent(self):
        """Autoplay all pending opponent replies from expected line."""
        if not self._expected:
            return

        # Play while it's opponent's turn and there are moves left
        self._autoplaying = True
        try:
            while self._expected and self._board_truth.turn != self._user_color:
                next_reply_uci = self._expected[0]
                reply_move = chess.Move.from_uci(next_reply_uci)

                if reply_move not in self._board_truth.legal_moves:
                    # Defensive: stop autoplay if something is inconsistent
                    break

                # Push to truth board and pop from expected
                self._board_truth.push(reply_move)
                self._expected.pop(0)

                # UI board will animate via ChessBoard.apply_move() in MainWindow.
                # We ONLY change the truth board here; UI board will be instructed to mirror.
                # Emitting moveResult here is optional; we keep things quiet for now.
        finally:
            self._autoplaying = False

    # ---------- Parsing utilities ----------

    def _parse_puzzles(
        self, raw: List[Union[Tuple[str, Union[str, List[str]]], str]]
    ) -> List[Puzzle]:
        out: List[Puzzle] = []
        for item in raw:
            if isinstance(item, tuple) and len(item) == 2:
                fen, moves = item
                fen = (fen or "").strip()
                if not fen:
                    continue
                line_uci = self._to_uci_line_from_fen_and_moves(fen, moves)
                out.append(Puzzle(start_fen=fen, line_uci=line_uci, title="FEN puzzle"))
            elif isinstance(item, str):
                # treat as PGN string
                parsed = self._parse_pgn_to_puzzle(item)
                if parsed:
                    out.append(parsed)
        return out

    def _to_uci_line_from_fen_and_moves(
        self, fen: str, moves: Union[str, List[str]]
    ) -> List[str]:
        brd = chess.Board(fen)
        tokens: List[str]
        if isinstance(moves, str):
            # Split by whitespace, strip move numbers like "1.", "2." if present
            raw = moves.strip()
            tokens = [t for t in re.split(r"\s+", raw) if t]
        else:
            tokens = list(moves)

        uci_line: List[str] = []
        for tok in tokens:
            # Skip move numbers and result markers
            if re.match(r"^\d+\.+$", tok) or tok in ("*", "1-0", "0-1", "1/2-1/2"):
                continue

            # Try SAN first, then UCI
            move_obj: Optional[chess.Move] = None
            try:
                move_obj = brd.parse_san(tok)
            except ValueError:
                # Try UCI
                try:
                    move_obj = chess.Move.from_uci(tok)
                    if move_obj not in brd.legal_moves:
                        raise ValueError
                except Exception:
                    raise ValueError(f"Unrecognized move token '{tok}' for FEN:\n{fen}")

            # Normalize to UCI, push
            uci_line.append(move_obj.uci())
            brd.push(move_obj)
        return uci_line

    def _parse_pgn_to_puzzle(self, pgn_str: str) -> Optional[Puzzle]:
        try:
            game = chess.pgn.read_game(StringIO(pgn_str))
            if game is None:
                return None
            brd = game.board()  # initial position (respects FEN in headers if present)
            start_fen = brd.fen()
            line_uci: List[str] = []
            for mv in game.mainline_moves():
                line_uci.append(mv.uci())
                brd.push(mv)
            title = game.headers.get("Event", "PGN puzzle")
            return Puzzle(start_fen=start_fen, line_uci=line_uci, title=title)
        except Exception:
            return None


# ---- Session data containers -------------------------------------------------


@dataclass
class PuzzleRecord:
    index: Optional[int] = None  # 1-based puzzle index if available
    title: Optional[str] = None
    outcome: str = ""  # "solved" | "failed"
    played: Optional[str] = None  # user's last move (uci/san)
    expected: Optional[str] = None  # expected move if failed


@dataclass
class SessionResults:
    mode: str = "Free"  # "Free" | "Timed"
    total_seconds: int = 0
    elapsed_seconds: int = 0
    solved: int = 0
    failed: int = 0
    attempted: int = 0
    records: List[PuzzleRecord] = field(default_factory=list)


# ---- Main Window -------------------------------------------------------------


class MainWindow(QtWidgets.QMainWindow):
    """
    Chess puzzle trainer MainWindow with Free and Timed modes.
    - Does NOT modify your Puzzler class.
    - Wires up ChessBoard <-> Puzzler and adds session/timer UI.
    """

    def __init__(self, puzzler: Puzzler, parent=None):
        super().__init__(parent)
        self.puzzler = puzzler

        # --- state ---
        self.session_active: bool = False
        self.session_mode: str = "Free"  # "Free" | "Timed"
        self.remaining_seconds: int = 0
        self.total_seconds: int = 0
        self.results = SessionResults()

        # track if we are between puzzles to avoid double counts
        self._waiting_next_after_result: bool = False

        # --- timers ---
        self.countdown_timer = QtCore.QTimer(self)
        self.countdown_timer.setInterval(1000)  # 1 sec
        self.countdown_timer.timeout.connect(self._on_tick)

        # --- UI ---
        self._build_ui()
        self._wire_signals()

        # Initial cosmetic state
        self._set_timer_visible(False)
        self._set_controls_enabled(free_mode=True)

    # ------------------------- UI Construction --------------------------------

