    def _wire_signals(self):
        # Board -> Puzzler
        self.board.moveMade.connect(self._on_user_move)

        # Puzzler -> UI
        # TODO: If your signal names differ, replace below accordingly.
        self.puzzler.puzzleChanged.connect(self._on_puzzle_changed)
        self.puzzler.moveResult.connect(self._on_move_result)

        # Buttons
        self.btn_start.clicked.connect(self._on_start_clicked)
        self.btn_next.clicked.connect(self._on_next_clicked)
        self.btn_retry.clicked.connect(self._on_retry_clicked)
        self.btn_hint.clicked.connect(self._on_hint_clicked)

        # Mode changes
        self.cmb_mode.currentTextChanged.connect(self._on_mode_changed)

    # ----------------------------- Event Handlers -----------------------------

    @QtCore.pyqtSlot()
    def _on_start_clicked(self):
        mode = self.cmb_mode.currentText()
        if mode == "Timed":
            self._start_timed_session()
        else:
            self._start_free_session()

    def _start_free_session(self):
        # No timer; enable manual controls
        self.session_mode = "Free"
        self.session_active = True
        self._set_timer_visible(False)
        self._set_controls_enabled(free_mode=True)
        self._reset_results(keep_mode=True, seconds=0)
        self.lbl_status.setText("Free mode: solve at your own pace.")
        # Optional: move to the first puzzle if needed

    def _start_timed_session(self):
        self.session_mode = "Timed"
        self.remaining_seconds = int(self.spin_seconds.value())
        self.total_seconds = self.remaining_seconds
        self._reset_results(keep_mode=True, seconds=self.total_seconds)

        self._set_timer_visible(True)
        self._update_timer_label()

        # Lock mode/duration, lock manual next/retry; hint optional (disabled here)
        self._set_controls_enabled(free_mode=False)

        # Start timer
        self.session_active = True
        self.countdown_timer.start()
        self.lbl_status.setText("Timed mode started. Good luck!")
        # Ensure we are on a puzzle; if your puzzler needs a kick, uncomment:
        # self.puzzler.next_puzzle()

    def _on_mode_changed(self, text: str):
        # Only influencing visibility before session starts
        if not self.session_active:
            timed = text == "Timed"
            self.lbl_time.setEnabled(timed)
            self.spin_seconds.setEnabled(timed)
            self._set_timer_visible(False)

    @QtCore.pyqtSlot()
    def _on_next_clicked(self):
        # Manual Next only in Free mode
        if self.session_mode == "Free":
            self.puzzler.next_puzzle()

    @QtCore.pyqtSlot()
    def _on_retry_clicked(self):
        # Retry current puzzle (if Puzzler provides it)
        if self.session_mode == "Free":
            if hasattr(self.puzzler, "retry_puzzle"):
                self.puzzler.retry_puzzle()
            else:
                # Fallback: just reload current via next->previous if you track index outside
                self.lbl_status.setText("Retry not available in this build of Puzzler.")

    @QtCore.pyqtSlot()
    def _on_hint_clicked(self):
        if hasattr(self.puzzler, "request_hint"):
            self.puzzler.request_hint()
        else:
            self.lbl_status.setText("Hint not available in this build of Puzzler.")

    @QtCore.pyqtSlot(str)
    def _on_user_move(self, uci: str):
        # Board finished applying user move; ask Puzzler to judge
        if hasattr(self.puzzler, "check_move"):
            self.puzzler.check_move(uci)

    @QtCore.pyqtSlot(str, dict)
    def _on_puzzle_changed(self, fen: str, info: Dict[str, Any]):
        # Orient board side if info contains color; otherwise keep current
        self.board.update_board(fen)

        # Title and index
        idx = info.get("puzzle_index")
        total = info.get("total_puzzles")
        title = info.get("title") or "Puzzle"
        hdr = f"{title}"
        if idx and total:
            hdr += f"  ({idx}/{total})"
        self.lbl_title.setText(hdr)

        # Give the board focus so user can move immediately
        self.board.setFocus()

    @QtCore.pyqtSlot(bool, str, dict)
    def _on_move_result(self, correct: bool, fen: str, info: Dict[str, Any]):
        """
        Timed:
          - wrong -> count failed, auto-next
          - solved -> count solved, auto-next
          - correct but not solved -> continue same puzzle
        Free:
          - just show feedback; user controls Next/Retry
        """
        # Always sync board with truth position received
        self.board.update_board(fen)

        # Pretty feedback
        if correct:
            self.lbl_status.setStyleSheet("color:#166534;")  # green-700
            msg = "Correct"
        else:
            self.lbl_status.setStyleSheet("color:#991b1b;")  # red-800
            msg = "Wrong"

        # Enrich message with details if provided
        played = info.get("played")
        expected = info.get("expected")
        if not correct and expected:
            msg += f" — expected {expected}"
        elif played:
            msg += f" — played {played}"
        self.lbl_status.setText(msg)

        # Free mode: done
        if self.session_mode == "Free":
            return

        # Timed mode: auto-advance policy
        if not self.session_active:
            return  # session may have ended on tick

        # Avoid double-next if we’re already scheduling one
        if self._waiting_next_after_result:
            return

        # Determine outcome for counting
        solved = bool(info.get("solved"))
        remaining = info.get("remaining")
        if correct and (solved or remaining == 0):
            self._count_outcome("solved", info)
            self._schedule_auto_next()
        elif not correct:
            self._count_outcome("failed", info)
            self._schedule_auto_next()
        else:
            # still in the same (multi-move) puzzle
            pass

    # ------------------------------- Timer ------------------------------------

    def _on_tick(self):
        # End session if time runs out
        if self.remaining_seconds > 0:
            self.remaining_seconds -= 1
            self._update_timer_label()

        # Check if all puzzles are finished
        puzzles_finished = False
        # Option 1: If you track attempted vs total
        if self.results.attempted >= self.puzzler.total_puzzles:
            puzzles_finished = True
        # Option 2: If Puzzler exposes is_finished
        # if getattr(self.puzzler, "is_finished", False):
        #     puzzles_finished = True

        if self.remaining_seconds <= 0 or puzzles_finished:
            self._finish_session()

    def _update_timer_label(self):
        mm = self.remaining_seconds // 60
        ss = self.remaining_seconds % 60
        self.lbl_timer.setText(f"{mm:02d}:{ss:02d}")
        # color cue: last 10 seconds red
        color = "#1f2937" if self.remaining_seconds > 10 else "#b91c1c"
        self.lbl_timer.setStyleSheet(f"color:{color}")

    # ----------------------------- Session Logic ------------------------------

    def _reset_results(self, keep_mode: bool = True, seconds: int = 0):
        self.results = SessionResults(
            mode=self.session_mode if keep_mode else "Free",
            total_seconds=seconds,
            elapsed_seconds=0,
            solved=0,
            failed=0,
            attempted=0,
            records=[],
        )
        self._render_score()

    def _count_outcome(self, outcome: str, info: Dict[str, Any]):
        # outcome: "solved" | "failed"
        rec = PuzzleRecord(
            index=info.get("puzzle_index"),
            title=info.get("title"),
            outcome=outcome,
            played=info.get("played"),
            expected=info.get("expected"),
        )
        self.results.records.append(rec)
        if outcome == "solved":
            self.results.solved += 1
        elif outcome == "failed":
            self.results.failed += 1
        self.results.attempted = self.results.solved + self.results.failed
        self._render_score()

    def _schedule_auto_next(self):
        # short delay to let user see feedback
        self._waiting_next_after_result = True
        QtCore.QTimer.singleShot(350, self._do_auto_next)

    def _do_auto_next(self):
        self._waiting_next_after_result = False
        if self.session_active:
            self.puzzler.next_puzzle()

    def _finish_session(self):
        if not self.session_active:
            return
        self.session_active = False
        self.countdown_timer.stop()

        self.results.elapsed_seconds = (
            self.results.total_seconds - self.remaining_seconds
        )
        self.remaining_seconds = 0
        self._update_timer_label()

        # Freeze inputs
        self.board.setDisabled(True)
        self._set_controls_enabled(free_mode=True, during_summary=True)

        # Summary dialog
        self._show_summary_dialog()

    def _show_summary_dialog(self):
        solved = self.results.solved
        failed = self.results.failed
        attempted = self.results.attempted
        mm = self.results.elapsed_seconds // 60
        ss = self.results.elapsed_seconds % 60

        text = (
            f"<h3>Session complete</h3>"
            f"<p><b>Mode:</b> {self.results.mode}<br>"
            f"<b>Time used:</b> {mm:02d}:{ss:02d}<br>"
            f"<b>Solved:</b> {solved} &nbsp;&nbsp; "
            f"<b>Failed:</b> {failed} &nbsp;&nbsp; "
            f"<b>Attempted:</b> {attempted}</p>"
        )
        msg = QtWidgets.QMessageBox(self)
        msg.setIcon(QtWidgets.QMessageBox.Information)
        msg.setWindowTitle("Summary")
        msg.setTextFormat(QtCore.Qt.RichText)
        msg.setText(text)
        msg.addButton("OK", QtWidgets.QMessageBox.AcceptRole)
        msg.exec_()

        # Re-enable board for subsequent free play
        self.board.setDisabled(False)
        self.lbl_status.setText(
            "Session complete. You can start a new session or switch to Free mode."
        )

    # Public: you can call this to save to DB later
    def get_session_results(self) -> SessionResults:
        return self.results

    # --------------------------- UI Helpers -----------------------------------

    def _set_timer_visible(self, visible: bool):
        self.lbl_timer.setVisible(visible)

    def _set_controls_enabled(self, free_mode: bool, during_summary: bool = False):
        """Enable/disable UI affordances depending on mode."""
        if free_mode:
            # Free or after summary
            self.cmb_mode.setEnabled(True)
            self.spin_seconds.setEnabled(self.cmb_mode.currentText() == "Timed")
            self.btn_start.setEnabled(True)

            # In free: manual navigation allowed
            self.btn_next.setEnabled(True)
            self.btn_retry.setEnabled(True)
            self.btn_hint.setEnabled(True)
        else:
            # Timed session running: lock mode, duration, and manual nav
            self.cmb_mode.setEnabled(False)
            self.spin_seconds.setEnabled(False)
            self.btn_start.setEnabled(False)

            self.btn_next.setEnabled(False)
            self.btn_retry.setEnabled(False)
            # Optional: disable hints in timed sessions to keep scoring clean
            self.btn_hint.setEnabled(False)

        # When just finished, keep Start enabled so user can start again
        if during_summary:
            self.btn_start.setEnabled(True)

    def _render_score(self):
        self.lbl_score.setText(
            f"Solved: {self.results.solved}   "
            f"Failed: {self.results.failed}   "
            f"Attempted: {self.results.attempted}"
        )


